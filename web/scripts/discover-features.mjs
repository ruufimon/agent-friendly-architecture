// Rule 4: features are discovered from the reserved file feature.ts in each folder.
// This writes src/app/features.generated.ts, which is git-ignored so it can never conflict.
import { existsSync, readdirSync, writeFileSync } from 'node:fs';

const dir = 'src/app/features';
const names = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(`${dir}/${d.name}/feature.ts`))
  .map((d) => d.name)
  .sort();

const ident = (name) => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const source = `// Generated by scripts/discover-features.mjs. Do not edit.
// To add a feature, create src/app/features/<name>/feature.ts (AGENTS.md, rule 4).
import type { Feature } from './dune/feature';
${names.map((n) => `import { feature as ${ident(n)} } from './features/${n}/feature';`).join('\n')}

export const features: Feature[] = [${names.map(ident).join(', ')}];
`;

writeFileSync('src/app/features.generated.ts', source);
console.log(`Discovered ${names.length} features: ${names.join(', ')}`);
